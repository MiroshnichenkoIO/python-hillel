#!/bin/bash
# Скрипт 1: знайомство з користувачем.
# Показує найпростіший ввід: команда read кладе те, що набрав користувач, у змінну.
#
# Запуск:  bash hello.sh

echo "=== Знайомство ==="

# -p виводить підказку і чекає на ввід у тому самому рядку
read -p "Як тебе звати? " name

# Якщо користувач нічого не ввів (порожній рядок) — підставляємо значення за замовчуванням.
# -z перевіряє «змінна порожня?»
if [ -z "$name" ]; then
    name="незнайомець"
fi

read -p "Скільки тобі років? $name, вкажи число: " age

# =~ порівнює з регулярним виразом: ^[0-9]+$ означає «лише цифри від початку до кінця»
if ! [[ "$age" =~ ^[0-9]+$ ]]; then
    echo "Це не схоже на число. Наступного разу введи, наприклад, 12."
    exit 1
fi

year=$(date +%Y)
born=$((year - age))

echo
echo "Привіт, $name!"
echo "Тобі $age років, отже ти народився приблизно у $born році."

if [ "$age" -lt 18 ]; then
    echo "Ти ще школяр — саме час вчити Python."
else
    echo "Дорослий програміст — теж чудово!"
fi
