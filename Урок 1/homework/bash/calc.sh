#!/bin/bash
# Скрипт 3: калькулятор у терміналі.
# Показує: цикл while, вибір із меню (case) і перевірку помилок.
#
# Запуск:  bash calc.sh

echo "=== Калькулятор ==="
echo "Для виходу введи q замість числа."

while true; do
    # `|| break` — вихід, якщо ввід закінчився (Ctrl+D)
    read -p $'\nПерше число: ' a || break

    if [ "$a" = "q" ]; then
        echo "Бувай!"
        break
    fi

    read -p "Друге число: " b || break

    # Обидва значення мають бути цілими числами (можливо, від'ємними)
    if ! [[ "$a" =~ ^-?[0-9]+$ ]] || ! [[ "$b" =~ ^-?[0-9]+$ ]]; then
        echo "Потрібні цілі числа, спробуй ще раз."
        continue
    fi

    read -p "Дія (+ - * /): " op || break

    # case — це вибір із кількох варіантів, схожий на if/elif/else, але коротший
    case "$op" in
        +) echo "Результат: $((a + b))" ;;
        -) echo "Результат: $((a - b))" ;;
        \*) echo "Результат: $((a * b))" ;;
        /)
            if [ "$b" -eq 0 ]; then
                echo "На нуль ділити не можна!"
            else
                echo "Результат: $((a / b)) (ціла частина), залишок: $((a % b))"
            fi
            ;;
        *) echo "Невідома дія '$op'. Доступні: + - * /" ;;
    esac
done
