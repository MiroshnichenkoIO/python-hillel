# --- 1. print(): кілька значень, sep і end ---

print("a", "b", "c")                  # a b c — між значеннями пробіл
print("a", "b", "c", sep="")          # abc   — без розділювача
print("a", "b", "c", sep=", ")        # a, b, c
print("2026", "08", "18", sep="-")    # 2026-08-18

print("без переносу...", end="")      # end замінює \n у кінці
print(" продовження в тому ж рядку")

print()                               # порожній рядок
print("рядок1\nрядок2")               # той самий перенос вручну


# --- 2. input(): читає рядок з клавіатури ---

name = input("Як тебе звати? ")
print(f"Привіт, {name}!")
print(type(name))          # <class 'str'> — ЗАВЖДИ рядок


# --- 3. Число з input() — обов'язково через int() / float() ---

age_raw = input("Скільки тобі років? ")
age = int(age_raw)                      # без цього рядка «age + 1» зламається
print(f"Наступного року буде {age + 1}")

# Частіше пишуть коротше, одним рядком:
height = float(input("Твій зріст у метрах (напр. 1.82): "))
print(f"Зріст у сантиметрах: {height * 100:.0f}")


# --- 4. Захист від «не числа» ---

raw = input("Введи ціле число: ").strip()
if raw.lstrip("-").isdigit():           # lstrip("-") — щоб пройшли й від'ємні
    print(f"Квадрат числа: {int(raw) ** 2}")
else:
    print(f"«{raw}» — це не ціле число")


# --- 5. Кілька значень з одного рядка ---

# Користувач вводить: 3 7
parts = input("Введи два числа через пробіл: ").split()
first, second = int(parts[0]), int(parts[1])
print(f"Сума: {first + second}")

# Той самий код у стислій формі:
# a, b = map(int, input().split())


# --- 6. .strip() та .lower() — гігієна введених даних ---

answer = input("Продовжити? (так/ні): ").strip().lower()
# strip() приберає випадкові пробіли, lower() — робить "ТАК" і "Так" однаковими
if answer in ("так", "т", "yes", "y"):
    print("Продовжуємо")
else:
    print("Зупиняємось")
