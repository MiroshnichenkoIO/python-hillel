"""Числа: int, float і всі операції з ними."""

from decimal import Decimal

# --- 1. Два основних числових типи ---

whole = 42            # int   — ціле, будь-якої довжини
fraction = 3.5        # float — з дробовою частиною
big = 10 ** 30        # int не має межі, на відміну від багатьох мов
print(whole, fraction, big)

# Підкреслення для читабельності великих чисел
salary = 1_500_000
print(salary)         # 1500000


# --- 2. Арифметика ---

print(7 + 3)      # 10   додавання
print(7 - 3)      # 4    відніманняv
print(7 * 3)      # 21   множення
print(7 / 3)      # 2.3333333333333335 — ДІЛЕННЯ ЗАВЖДИ ДАЄ float
print(7 // 3)     # 2    ділення з відкиданням дробової частини
print(7 % 3)      # 1    остача від ділення
print(7 ** 3)     # 343  піднесення до степеня

print(10 / 2)         # 5.0 — теж float, хоча ділиться без остачі!
print(type(10 / 2))   # <class 'float'>


# --- 3. Де це потрібно на практиці ---

# % — перевірка на кратність (парне число, кожен третій крок тощо)
number = 14
print(number % 2 == 0)   # True — число парне

# // — «скільки цілих разів вміщується»
total_minutes = 145
print(total_minutes // 60, "год", total_minutes % 60, "хв")   # 2 год 25 хв


# --- 4. Скорочені оператори ---

counter = 0
counter += 1      # те саме, що counter = counter + 1
counter += 5
counter -= 2
counter *= 3
print(counter)    # 12
# У Python немає counter++ — тільки counter += 1


# --- 5. Пастка float: гроші у float не рахують ---

print(0.1 + 0.2)             # 0.30000000000000004
print(0.1 + 0.2 == 0.3)      # False (!)

# float зберігається у двійковому вигляді, і 0.1 у ньому не має точного запису.
# Для грошей та точних розрахунків беремо Decimal (рядок у лапках — обов'язково):
print(Decimal("0.1") + Decimal("0.2"))                     # 0.3
print(Decimal("0.1") + Decimal("0.2") == Decimal("0.3"))   # True


# --- 6. Округлення ---

print(round(3.7))         # 4
print(round(3.14159, 2))  # 3.14
print(round(2.5))         # 2 (!) — «банківське» округлення до найближчого парного
print(round(3.5))         # 4
print(abs(-7))            # 7 — модуль числа


# --- 7. Корисні вбудовані функції ---

print(min(3, 9, 1))      # 1
print(max(3, 9, 1))      # 9
print(sum([1, 2, 3]))    # 6
print(divmod(7, 3))      # (2, 1) — одразу // і % однією дією
