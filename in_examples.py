# Оператор "in" — проверка вхождения.
# Отвечает на вопрос "есть ли элемент внутри?" и возвращает True или False.

# --- 1. Строки: ищем ПОДСТРОКУ ---

text = "Привет, мир"

print("мир" in text)        # True  — такая подстрока есть
print("Мир" in text)        # False — регистр важен!
print("вет," in text)       # True  — куски слов тоже находятся
print("z" not in text)      # True  — "not in" это отдельный оператор, не "not (x in y)"

# Практический приём: приводим к одному регистру перед проверкой
answer = "ДА"
print("да" in answer.lower())   # True


# --- 2. Списки: ищем ЭЛЕМЕНТ ЦЕЛИКОМ ---

numbers = [1, 2, 3, 10]

print(3 in numbers)         # True
print(5 in numbers)         # False
print(0 in numbers)         # False — важно: 0 нет в списке, хотя это "ложное" значение

# Ловушка: в списке ищется элемент целиком, а не его часть
words = ["кот", "собака"]
print("кот" in words)       # True  — есть такой элемент
print("ко" in words)        # False — а вот в СТРОКЕ "ко" in "кот" дало бы True

# Разница со строкой:
print("ко" in "кот")        # True — здесь ищем подстроку


# --- 3. Кортежи и множества ---

vowels = ("а", "е", "и", "о", "у")
print("е" in vowels)        # True — кортеж работает как список

allowed = {"да", "нет", "yes", "no"}    # множество (set), фигурные скобки
print("нет" in allowed)     # True
# Для множества проверка "in" работает МГНОВЕННО, независимо от размера,
# а для списка Python перебирает элементы по одному.
# На 10 элементах разницы нет, на 100 000 — огромная.


# --- 4. Словари: "in" ищет по КЛЮЧАМ, не по значениям ---

person = {"name": "Игорь", "age": 30}

print("name" in person)             # True  — есть такой ключ
print("Игорь" in person)            # False — это значение, а не ключ!
print("Игорь" in person.values())   # True  — так ищем по значениям


# --- 5. Зачем это нужно: "in" вместо длинной цепочки or ---

command = input("Введите команду (стоп/выход/quit): ").strip().lower()

# Плохо — длинно и легко ошибиться:
# if command == "стоп" or command == "выход" or command == "quit":

# Хорошо:
if command in ("стоп", "выход", "quit"):
    print("Завершаем работу")
else:
    print("Неизвестная команда:", command)


# --- 6. Второе значение "in": перебор в цикле for ---

# Здесь "in" — НЕ проверка, а часть синтаксиса цикла: "для каждого x из ..."
for letter in "код":
    print("буква:", letter)

for n in [10, 20, 30]:
    print("число:", n)

# Одно и то же слово, два разных смысла — различайте по контексту:
#   if x in y:   -> проверка, результат True/False
#   for x in y:  -> перебор, x по очереди принимает значения из y


# --- 7. Комбинация: фильтрация списка (как в вашем lesson_01.py) ---

a = list(range(9))          # [0..8]
c = a + list(range(6))      # [0..8, 0..5] — есть повторы

unique = [x for x in c if x not in a]
print("элементы c, которых нет в a:", unique)   # [] — все они есть в a

big = [x for x in c if x in (7, 8)]
print("только 7 и 8:", big)
